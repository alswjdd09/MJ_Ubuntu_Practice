#include <stdio.h>

// 앞의 예제를 포인터 배열을 적용해서 작성
int main(void){
    // 실제 숫자 데이터를 저장할 5행 6열 2차원 배열
    int ary[5][6];
    // ary의 각 요소의 주소를 저장할 포인터 배열 -> pary[i][j]에는 ary[i][j]의 "주소"가 들어간다.
    int *pary[5][6];

    int i, j;
    int cnt = 1;
    int total;


    // --------------------------------------------------
    // 1. 포인터 배열과 실제 데이터 배열 연결 + 1~20 저장
    // --------------------------------------------------
    // 4행까지만 사용 (0~3행)
    // 마지막 5행은 각 열의 합을 저장하기 위해 남겨둔다.
    for(i = 0; i < 4; i++){
        // 5열까지 사용 (0~4열)
        // 마지막 6열은 각 행의 합을 저장하기 위해 남겨둔다.
        for(j = 0; j < 5; j++){
            // pary[i][j]에 ary[i][j]의 주소를 저장
            // & : 변수의 주소를 구한다.
            // 예 : pary[0][0] = &ary[0][0]; 즉, pary[0][0]은 ary[0][0]을 가리킨다.
            pary[i][j] = &ary[i][j];

            // pary[i][j]가 ary[i][j]의 주소를 가지고 있으므로
            // *pary[i][j]를 통해 ary[i][j]에 값을 저장할 수 있다.
            *pary[i][j] = cnt;

            // 다음 숫자로 증가
            cnt++;
        }
    }


    // --------------------------------------------------
    // 2. 각 행의 합을 구해서 마지막 열에 저장
    // --------------------------------------------------
    // 0~3행의 합을 각각 계산
    for(i = 0; i < 4; i++){
        // 새로운 행의 합을 계산하기 전에 0으로 초기화
        total = 0;

        // 현재 행의 0~4열을 차례대로 더한다.
        for(j = 0; j < 5; j++){
            // pary[i][j]는 주소이고
            // *pary[i][j]는 그 주소에 저장된 실제 값이다.
            //
            // 예:
            // *pary[0][0] → 1
            // *pary[0][1] → 2
            // ...
            total += *pary[i][j];
        }

        // 마지막 열(5번 열)에 저장할 공간의 주소를 연결
        pary[i][5] = &ary[i][5];

        // 계산한 행의 합을 마지막 열에 저장
        *pary[i][5] = total;
    }


    // --------------------------------------------------
    // 3. 각 열의 합을 구해서 마지막 행에 저장
    // --------------------------------------------------
    // 0~4열을 하나씩 선택
    for(j = 0; j < 5; j++){
        // 새로운 열의 합을 계산하기 전에 0으로 초기화
        total = 0;

        // 현재 열의 0~3행을 차례대로 더한다.
        for(i = 0; i < 4; i++){
            // 현재 열의 값을 가져와서 total에 더한다.
            //
            // pary[i][j] → 주소
            // *pary[i][j] → 실제 값
            total += *pary[i][j];
        }

        // 마지막 행(4번 행)의 해당 열과 연결
        pary[4][j] = &ary[4][j];

        // 계산한 열의 합을 마지막 행에 저장
        *pary[4][j] = total;
    }


    // --------------------------------------------------
    // 4. 전체 합 구하기
    // --------------------------------------------------
    total = 0;

    // 각 행의 합이 저장되어 있는 마지막 열을 더한다.
    // ary[0][5] = 15
    // ary[1][5] = 40
    // ary[2][5] = 65
    // ary[3][5] = 90
    // 15 + 40 + 65 + 90 = 210
    for(i = 0; i < 4; i++){
        // 포인터를 이용해서 마지막 열의 값을 가져온다.
        total += *pary[i][5];
    }

    // 마지막 행의 마지막 열과 연결
    pary[4][5] = &ary[4][5];

    // 전체 합을 마지막 칸에 저장
    *pary[4][5] = total;


    // --------------------------------------------------
    // 5. 전체 배열 출력
    // --------------------------------------------------
    // 5행을 차례대로 출력
    for(i = 0; i < 5; i++){
        // 각 행의 6열을 차례대로 출력
        for(j = 0; j < 6; j++){
            // pary[i][j]는 주소이므로
            // *를 붙여 실제 값을 출력한다.
            printf("%5d", *pary[i][j]);
        }

        // 한 행이 끝나면 줄바꿈
        printf("\n");
    }


    return 0;
}